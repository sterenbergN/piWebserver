// Rebuild lib/movies-data.ts — the movie picker's list — from IMDb's
// official datasets (https://developer.imdb.com/non-commercial-datasets/,
// free for personal, non-commercial use):
//
//   node scripts/update-movie-list.mjs
//
// Ranking follows IMDb's published Top 250 formula: a Bayesian average
//   WR = v/(v+m)·R + m/(v+m)·C
// with m = 25,000 votes (the Top 250 minimum) and C the mean rating of the
// eligible films, so a film needs both a high rating and many votes.
// Only feature films count (no TV, shorts or documentaries). IMDb also
// weights "regular voters", which its data doesn't expose, so a few places
// can differ from imdb.com/chart/top. Films from the current year are left
// out until they've been out a while.
import { createGunzip } from 'node:zlib';
import { createInterface } from 'node:readline';
import { Readable } from 'node:stream';
import fs from 'node:fs/promises';

const BASE = 'https://datasets.imdbws.com';
const MIN_VOTES = 25_000;
const COUNT = 1000;
const OUT = new URL('../lib/movies-data.ts', import.meta.url);

async function* lines(file) {
  const res = await fetch(`${BASE}/${file}`);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  const rl = createInterface({ input: Readable.fromWeb(res.body).pipe(createGunzip()), crlfDelay: Infinity });
  for await (const line of rl) {
    yield line;
  }
}

console.log('Reading ratings…');
const ratings = new Map();
let ratingsHeader = null;
let rTconstIdx = 0, rRatingIdx = 1, rVotesIdx = 2;
for await (const line of lines('title.ratings.tsv.gz')) {
  if (!ratingsHeader) {
    ratingsHeader = line.split('\t');
    rTconstIdx = ratingsHeader.indexOf('tconst');
    rRatingIdx = ratingsHeader.indexOf('averageRating');
    rVotesIdx = ratingsHeader.indexOf('numVotes');
    continue;
  }
  const cols = line.split('\t');
  const votes = Number(cols[rVotesIdx]);
  if (votes >= MIN_VOTES) {
    ratings.set(cols[rTconstIdx], { rating: Number(cols[rRatingIdx]), votes });
  }
}
console.log(`${ratings.size} titles with ${MIN_VOTES.toLocaleString()}+ votes`);

console.log('Reading titles (large file, streamed)…');
const films = [];
let basicsHeader = null;
let tconstIdx = 0, typeIdx = 1, titleIdx = 2, adultIdx = 4, yearIdx = 5, runtimeIdx = 7, genresIdx = 8;

for await (const line of lines('title.basics.tsv.gz')) {
  if (!basicsHeader) {
    basicsHeader = line.split('\t');
    tconstIdx = basicsHeader.indexOf('tconst');
    typeIdx = basicsHeader.indexOf('titleType');
    titleIdx = basicsHeader.indexOf('primaryTitle');
    adultIdx = basicsHeader.indexOf('isAdult');
    yearIdx = basicsHeader.indexOf('startYear');
    runtimeIdx = basicsHeader.indexOf('runtimeMinutes');
    genresIdx = basicsHeader.indexOf('genres');
    continue;
  }

  // Fast check on column 0 (tconst) to avoid splitting millions of irrelevant rows
  const firstTab = line.indexOf('\t');
  const tconst = firstTab === -1 ? line : line.slice(0, firstTab);
  const r = ratings.get(tconst);
  if (!r) continue;

  const cols = line.split('\t');
  if (cols[typeIdx] !== 'movie' || cols[adultIdx] === '1') continue;

  const rawGenres = cols[genresIdx];
  const genresList = rawGenres && rawGenres !== '\\N' ? rawGenres.split(',').filter(Boolean) : [];
  if (genresList.includes('Documentary')) continue;

  const minutes = Number(cols[runtimeIdx]);
  if (Number.isFinite(minutes) && minutes < 45) continue;

  // New releases open with inflated fan ratings; wait until a film has been out a full year.
  const year = Number(cols[yearIdx]);
  if (!year || year >= new Date().getFullYear()) continue;

  const runtime = Number.isFinite(minutes) ? minutes : 0;
  films.push({
    id: tconst,
    title: cols[titleIdx],
    year: year || null,
    genres: genresList,
    runtime,
    ...r
  });
}

const mean = films.reduce((s, f) => s + f.rating, 0) / films.length;
for (const f of films) f.score = (f.votes / (f.votes + MIN_VOTES)) * f.rating + (MIN_VOTES / (f.votes + MIN_VOTES)) * mean;
films.sort((a, b) => b.score - a.score || b.votes - a.votes);
const top = films.slice(0, COUNT);

const today = new Date().toISOString().slice(0, 10);
const body = top.map((f) => `  { id: ${JSON.stringify(f.id)}, title: ${JSON.stringify(f.title)}, year: ${f.year}, rating: ${f.rating}, genres: ${JSON.stringify(f.genres)}, runtime: ${f.runtime} },`).join('\n');
await fs.writeFile(OUT, `// IMDb top ${COUNT} feature films, rebuilt from IMDb's datasets on ${today}.
// Generated by scripts/update-movie-list.mjs — run it again to refresh; don't edit by hand.
// Information courtesy of IMDb (https://www.imdb.com). Used with permission for personal, non-commercial use.

export type Film = { id: string; title: string; year: number | null; rating: number; genres: string[]; runtime: number; };

export const TOP_FILMS: Film[] = [
${body}
];
`);
console.log(`Wrote ${top.length} films (mean rating of eligible films ${mean.toFixed(2)}).`);
console.log(top.slice(0, 10).map((f, i) => `${i + 1}. ${f.title} (${f.year}) ${f.rating} [${f.genres.join(', ')}] ${f.runtime}m`).join('\n'));
